"""The Git publication worker (FR-GIT-04, FR-GIT-05, FR-GIT-09, NFR-DEP-07).

``GitPublisher`` drains one repository's outbox strictly in ``seq`` order under an in-process
lock. Each attempt renders the stored snapshot over the current remote tip, commits once and
pushes, directly or to a ``lakeloom/<slug>/<proposal-id>`` branch with a pull request. A
rejected push resets to the new tip and renders again (never ``git rebase``). Before any
commit the remote is searched for the ``Lakeloom-Publication`` trailer, so a retry after a
crash never commits twice. Failures are classified (ADR 0013 § Retry): transient ones stay
``pending`` with exponential backoff, permanent ones become ``blocked`` and stop the queue.
"""

from __future__ import annotations

import asyncio
import hashlib
import logging
import re
import weakref
from collections.abc import Awaitable, Callable
from datetime import UTC, datetime, timedelta
from typing import Any

from lakeloom import metrics
from lakeloom.config import Settings
from lakeloom.gitstore.forge import Forge
from lakeloom.gitstore.git import GitError, redact
from lakeloom.gitstore.layout import Snapshot, render
from lakeloom.gitstore.repo import WorkingCopy
from lakeloom.state.publications import Publication, PublicationRepository

__all__ = ["INITIAL_MESSAGE", "INITIAL_README", "GitPublisher", "backoff_seconds", "utcnow"]

logger = logging.getLogger(__name__)

INITIAL_README = b"# Ontologies\n\nGenerated by Lakeloom.\n"
INITIAL_MESSAGE = "chore: initialise ontology repository"
TRAILER_KEY = "Lakeloom-Publication"
MAX_RERENDERS = 3
BACKOFF_BASE = 60
BACKOFF_MAX = 3600
ERROR_MAX = 500

_TRANSIENT_KINDS = frozenset({"network", "timeout", "rejected"})
_MANIFEST = re.compile(r"^ontologies/([^/]+)/manifest\.yaml$")

Exporter = Callable[[Snapshot], Awaitable[Snapshot]]

# One lock per repository and event loop (asyncio locks must not cross loops).
_LOCKS: weakref.WeakKeyDictionary[asyncio.AbstractEventLoop, dict[str, asyncio.Lock]] = (
    weakref.WeakKeyDictionary()
)


def utcnow() -> datetime:
    return datetime.now(UTC)


def backoff_seconds(attempts: int) -> int:
    """Delay before the next try after ``attempts`` failed ones: 60 s doubling, max 1 h."""
    return min(BACKOFF_BASE * 2 ** max(attempts - 1, 0), BACKOFF_MAX)


def _lock(repo_key: str) -> asyncio.Lock:
    per_loop = _LOCKS.setdefault(asyncio.get_running_loop(), {})
    return per_loop.setdefault(repo_key, asyncio.Lock())


class _Transient(Exception):
    """A failure that is retried later (exporter missing or failing)."""


class GitPublisher:
    def __init__(
        self,
        settings: Settings,
        repo: PublicationRepository,
        working_copy: WorkingCopy | None,
        forge: Forge | None,
        *,
        exporter: Exporter | None = None,
        clock: Callable[[], datetime] = utcnow,
    ) -> None:
        self._settings = settings
        self._repo = repo
        self._wc = working_copy
        self._forge = forge
        self._exporter = exporter
        self._clock = clock
        remote = settings.git_remote or ""
        self.enabled: bool = bool(remote) and working_copy is not None
        self.repo_key: str = hashlib.sha256(remote.encode()).hexdigest() if self.enabled else ""

    # --- queue ----------------------------------------------------------------------------

    async def enqueue(self, pub: Publication) -> Publication:
        """Store ``pub`` for this repository (an existing one for the proposal wins).

        With Git disabled nothing is stored and ``pub`` is returned as is.
        """
        if not self.enabled:
            return pub
        return await self._repo.add(pub.model_copy(update={"repo": self.repo_key}))

    async def for_proposal(self, proposal_id: str) -> Publication | None:
        """The publication of a proposal (``None`` when Git is off or there is none)."""
        if not self.enabled:
            return None
        return await self._repo.for_proposal(proposal_id)

    async def retry_blocked(self) -> int:
        """``lakeloom git retry``: move blocked publications back to pending."""
        if not self.enabled:
            return 0
        async with _lock(self.repo_key):
            return await self._repo.requeue_blocked(self.repo_key)

    async def status(self) -> dict[str, Any]:
        """For ``server_info``: enabled, mode, pending and blocked counts, the head's error."""
        out: dict[str, Any] = {
            "enabled": self.enabled,
            "mode": self._settings.git_mode,
            "pending": 0,
            "blocked": 0,
            "last_error": None,
        }
        if not self.enabled:
            return out
        counts = await self._repo.counts(self.repo_key)
        head = await self._repo.head(self.repo_key)
        out.update(pending=counts["pending"], blocked=counts["blocked"])
        out["last_error"] = head.last_error if head is not None else None
        return out

    async def process(self, *, now: datetime | None = None) -> list[Publication]:
        """Publish the head while it is due and not blocked; returns the attempted rows.

        Never raises (except ``CancelledError``): every failure is recorded on the row, and a
        failure to record it is logged and retried on the next call.
        """
        if not self.enabled:
            return []
        done: list[Publication] = []
        async with _lock(self.repo_key):
            while True:
                at = now if now is not None else self._clock()
                try:
                    head = await self._repo.head(self.repo_key)
                except Exception as exc:
                    logger.warning("git publication queue unavailable: %s", _error_text(exc))
                    break
                if head is None or head.status == "blocked":
                    break
                if head.next_attempt_at is not None and head.next_attempt_at > at:
                    break
                result = await self._attempt(head, at)
                try:
                    await self._repo.update(result)
                except Exception as exc:
                    logger.warning(
                        "could not record git publication %s (%s): %s",
                        result.id,
                        result.status,
                        _error_text(exc),
                    )
                    break
                done.append(result)
                if result.status != "done":
                    break
        return done

    # --- one attempt ----------------------------------------------------------------------

    async def _attempt(self, pub: Publication, at: datetime) -> Publication:
        pub = pub.model_copy(deep=True)
        pub.updated_at = at
        try:
            await self._publish(pub)
        except asyncio.CancelledError:
            raise
        except GitError as exc:
            self._fail(pub, at, _error_text(exc), transient=exc.kind in _TRANSIENT_KINDS)
        except ValueError as exc:
            self._fail(pub, at, _error_text(exc), transient=False)
        except Exception as exc:  # exporter failures and anything unexpected
            self._fail(pub, at, _error_text(exc), transient=True)
        else:
            metrics.GIT_PUBLICATIONS.labels(result="done").inc()
            pub.status = "done"
            pub.next_attempt_at = None
            pub.last_error = None
            logger.info("published %s as %s on %s", pub.id, pub.commit_sha, pub.branch)
        return pub

    def _fail(self, pub: Publication, at: datetime, error: str, *, transient: bool) -> None:
        pub.attempts += 1
        pub.last_error = error
        if transient:
            pub.status = "pending"
            pub.next_attempt_at = at + timedelta(seconds=backoff_seconds(pub.attempts))
        else:
            pub.status = "blocked"
            pub.next_attempt_at = None
        result = "retry" if transient else "blocked"
        metrics.GIT_PUBLICATIONS.labels(result=result).inc()
        logger.warning("git publication %s %s: %s", pub.id, result, error)

    async def _publish(self, pub: Publication) -> None:
        """Bring ``pub`` onto the remote; sets ``commit_sha``, ``branch`` and ``pr_url``."""
        wc, forge = self._wc, self._forge
        if wc is None:
            raise GitError("failed", "git publishing is disabled (no LAKELOOM_GIT_REMOTE)")
        target = self._settings.git_branch
        if pub.mode == "pull_request" and forge is None:
            raise GitError("failed", "pull_request mode needs a forge (LAKELOOM_FORGE)")
        await wc.ensure()
        if await wc.remote_head(target) is None:
            await wc.init_branch(target, {"README.md": INITIAL_README}, INITIAL_MESSAGE)
            await self._push(wc, target, target)
        if pub.mode == "direct" or forge is None:
            pub.commit_sha = await self._commit_direct(wc, pub, target)
            pub.branch = target
            return
        branch = f"lakeloom/{pub.model}/{pub.proposal_id}"
        sha: str | None = None
        if await wc.remote_head(branch) is not None:
            await wc.checkout_tip(branch)
            sha = await wc.find_trailer(f"origin/{branch}", TRAILER_KEY, pub.id)
        if sha is None:
            sha = await self._commit_pr_branch(wc, pub, target, branch)
        pub.commit_sha = sha
        pub.branch = branch
        title, _, rest = pub.payload.message.partition("\n")
        pr = await forge.open_pull_request(
            head=branch, base=target, title=title.strip(), body=rest.lstrip("\n")
        )
        pub.pr_url = pr.url

    async def _commit_direct(self, wc: WorkingCopy, pub: Publication, target: str) -> str:
        for attempt in range(MAX_RERENDERS + 1):
            await wc.checkout_tip(target)
            found = await wc.find_trailer(f"origin/{target}", TRAILER_KEY, pub.id)
            if found is not None:
                return found
            sha = await self._write_and_commit(wc, pub)
            try:
                await self._push(wc, target, target)
            except GitError as exc:
                if exc.kind == "rejected" and attempt < MAX_RERENDERS:
                    logger.info("push of %s rejected; rendering on the new tip", pub.id)
                    continue
                raise
            return sha
        raise AssertionError("unreachable")  # pragma: no cover

    async def _commit_pr_branch(
        self, wc: WorkingCopy, pub: Publication, target: str, branch: str
    ) -> str:
        # The PR branch is Lakeloom's own: force-push, so a push is never rejected.
        await wc.start_branch(branch, target)
        sha = await self._write_and_commit(wc, pub)
        await self._push(wc, branch, branch, force=True)
        return sha

    async def _write_and_commit(self, wc: WorkingCopy, pub: Publication) -> str:
        snap = await self._exports(pub)
        slug = snap.model
        manifests: dict[str, bytes] = {}
        for path in wc.list_files("ontologies"):
            m = _MANIFEST.match(path)
            if m is not None and m.group(1) != slug and (data := wc.read(path)) is not None:
                manifests[m.group(1)] = data
        files = render(
            snap,
            pub.id,
            previous_manifest=wc.read(f"ontologies/{slug}/manifest.yaml"),
            previous_provenance=wc.read(f"provenance/{slug}.jsonl"),
            manifests=manifests,
        )
        wc.write(files)
        return await wc.commit(snap.message)

    async def _exports(self, pub: Publication) -> Snapshot:
        """The snapshot with its exports, exporting now when apply could not (transient)."""
        if pub.payload.exports is not None:
            return pub.payload
        if self._exporter is None:
            raise _Transient("snapshot has no exports and no exporter is configured")
        try:
            snap = await self._exporter(pub.payload)
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            raise _Transient(f"export failed: {_error_text(exc)}") from exc
        if snap.exports is None:
            raise _Transient("exporter returned no exports")
        pub.payload = snap
        return snap

    async def _push(self, wc: WorkingCopy, local: str, remote: str, *, force: bool = False) -> None:
        try:
            await wc.push(local, remote, force=force)
        except GitError:
            metrics.GIT_PUSH_FAILURES.inc()
            raise


def _error_text(exc: BaseException) -> str:
    text = str(exc) if isinstance(exc, GitError | _Transient) else f"{type(exc).__name__}: {exc}"
    return redact(text).strip()[:ERROR_MAX]
